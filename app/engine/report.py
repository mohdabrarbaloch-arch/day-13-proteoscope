"""Human-readable report generation and export formats.

Turns a prediction dict into a plain-text report, a CSV of the residue table,
or a minimal PDB file of the C-alpha trace.
"""

from __future__ import annotations

from app.engine.sequence import RESIDUE_MASS


def build_report(result: dict) -> str:
    """A plain-text report summarising a prediction."""
    seq = result["sequence"]
    ss = result["secondary_structure"]
    contacts = result["contacts"]
    struct = result["structure"]
    props = result.get("properties")

    lines: list[str] = []
    lines.append("=" * 60)
    lines.append("Proteoscope structure report")
    lines.append("=" * 60)
    lines.append(f"Sequence: {seq['header'] or '(unnamed)'}")
    lines.append(f"Length:   {seq['length']} residues")
    lines.append("")
    lines.append("Secondary structure (Chou-Fasman):")
    lines.append(f"  Helix: {ss['helix_fraction'] * 100:.1f}%")
    lines.append(f"  Sheet: {ss['sheet_fraction'] * 100:.1f}%")
    lines.append(f"  Turn:  {ss['turn_fraction'] * 100:.1f}%")
    lines.append(f"  Coil:  {ss['coil_fraction'] * 100:.1f}%")
    lines.append("")
    lines.append(f"Contacts: {contacts['count']} predicted")
    lines.append(f"Mean confidence: {struct['mean_confidence']:.2f}")
    lines.append(f"Radius of gyration: {struct['radius_of_gyration']:.1f} A")
    if props:
        lines.append("")
        lines.append("Physicochemical properties:")
        lines.append(f"  Molecular weight: {props['molecular_weight_da']:.1f} Da")
        lines.append(f"  Isoelectric point: {props['isoelectric_point']:.2f}")
        lines.append(f"  Charge at pH 7: {props['charge_at_ph7']:+.2f}")
        lines.append(f"  GRAVY: {props['gravy']:.2f}")
    lines.append("")
    lines.append("Per-residue assignments (H=helix E=sheet T=turn C=coil):")
    assignments = ss["assignments"]
    for start in range(0, len(assignments), 60):
        lines.append("  " + "".join(assignments[start : start + 60]))
    lines.append("")
    lines.append("Generated by Proteoscope v1.0.0 — deterministic, no ML weights.")
    return "\n".join(lines)


def to_csv(result: dict) -> str:
    """A CSV of the residue table: index, residue, mass, secondary structure."""
    seq = result["sequence"]["cleaned"]
    assignments = result["secondary_structure"]["assignments"]
    confidence = result["structure"]["confidence"]
    lines = ["index,residue,mass_da,secondary,confidence"]
    for i, aa in enumerate(seq):
        lines.append(
            f"{i + 1},{aa},{RESIDUE_MASS.get(aa, 0.0):.3f},{assignments[i]},{confidence[i]:.3f}"
        )
    return "\n".join(lines)


def to_pdb(result: dict) -> str:
    """A minimal PDB file of the C-alpha trace.

    Only the backbone CA atoms are written — enough to view the fold in any
    structure viewer, without pretending to be a full all-atom model.
    """
    seq = result["sequence"]["cleaned"]
    coords = result["structure"]["coordinates"]
    lines = ["HEADER    PROTEOSCOPE PREDICTED C-ALPHA TRACE"]
    for i, (aa, (x, y, z)) in enumerate(zip(seq, coords)):
        lines.append(
            f"ATOM  {i + 1:5d}  CA  {aa:3s} A{1:4d}    {x:8.3f}{y:8.3f}{z:8.3f}  1.00 20.00           C"
        )
    lines.append("END")
    return "\n".join(lines)